"""Provenance guards on the checked-in catalogue snapshot fixture (task 6.2).

`services/matcher/tests/data/catalogue_snapshot.json` is the offline stand-in
for the live Supabase catalogue: the eval suite measures REQ-ENG-6 against it,
so every accuracy number in `test_eval_accuracy.py` is only meaningful while
this file is exactly the export it claims to be. These are approval tests over
generated data -- they pin what the export produced (shape, counts, hash) and
what it must never contain (stock quantities, RF-18 data), so drift shows up as
a named failure instead of a silently different baseline.

The fixture is regenerated by `scripts/export_catalogue_snapshot.py`, which is
the only thing in this change that ever touches the network, is run by hand,
and is never executed by CI. Nothing in this file reaches Supabase.
"""
from __future__ import annotations

import hashlib
import importlib.util
import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[4]
FIXTURE_PATH = Path(__file__).resolve().parents[1] / "data" / "catalogue_snapshot.json"

FIXTURE_SHA256 = "c72c7429a25553e4cd4b76077779df4a5b4b4c51f8f5194a73dcbbb2d30c3430"

EXPECTED_ROW_COUNT = 1405

EXPECTED_WAREHOUSE_ROWS = {
    "STOCK_ALMACEN_AYB": 270,
    "STOCK_ALMACEN_SUMINISTROS": 296,
    "STOCK_KIOSCO_PISCIGIROS_AYB": 56,
    "STOCK_KIOSCO_TAQUILLA_AYB": 58,
    "STOCK_RESTAURANTE_FUENTES_AYB": 344,
    "STOCK_RESTAURANTE_FUENTES_SUMIN": 133,
    "ZOOLOGICO": 55,
    "ZOOLOGICO_SUMINISTROS_2": 193,
}

FIXTURE_LOADED_AT = "2026-07-25T00:00:00+00:00"
"""A fixed literal, not "now": re-exporting an unchanged catalogue must not diff."""


def load_remap_script():
    """Import the one-shot remap script; it lives outside any package."""
    path = REPO_ROOT / "scripts" / "remap_eval_set.py"
    spec = importlib.util.spec_from_file_location("remap_eval_set", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class TestSnapshotFixture:
    def test_the_fixture_parses_as_a_v1_snapshot(self) -> None:
        from matcher.cache import decode_snapshot

        snapshot = decode_snapshot(FIXTURE_PATH.read_bytes())
        assert snapshot is not None
        assert snapshot.loaded_at.isoformat() == FIXTURE_LOADED_AT
        assert len(snapshot.rows) == EXPECTED_ROW_COUNT

    def test_it_carries_the_expected_row_and_warehouse_counts(self) -> None:
        from matcher.cache import decode_snapshot
        from matcher.catalogue import group_rows

        snapshot = decode_snapshot(FIXTURE_PATH.read_bytes())
        assert snapshot is not None
        counts = {code: len(rows) for code, rows in group_rows(snapshot.rows).items()}
        assert counts == EXPECTED_WAREHOUSE_ROWS
        assert sum(counts.values()) == EXPECTED_ROW_COUNT

    def test_every_uid_is_distinct(self) -> None:
        rows = json.loads(FIXTURE_PATH.read_text(encoding="utf-8"))["rows"]
        assert len({row["uid"] for row in rows}) == EXPECTED_ROW_COUNT

    def test_it_names_no_stock_field(self) -> None:
        """REQ-RCC-5 / RF-18: no stock quantity may reach a cache or a fixture."""
        raw = FIXTURE_PATH.read_bytes()
        assert b'"sd"' not in raw
        assert b"theoretical_qty" not in raw
        assert b"cantidad" not in raw.lower()

    def test_its_sha256_is_pinned(self) -> None:
        assert hashlib.sha256(FIXTURE_PATH.read_bytes()).hexdigest() == FIXTURE_SHA256

    def test_it_round_trips_through_the_production_codec(self) -> None:
        """The fixture is exactly what `encode_snapshot` would write today."""
        from matcher.cache import decode_snapshot, encode_snapshot

        raw = FIXTURE_PATH.read_bytes()
        snapshot = decode_snapshot(raw)
        assert snapshot is not None
        assert encode_snapshot(snapshot) == raw


class TestWarehouseCodeMapping:
    """The `table -> warehouse code` map is NOT `upper()` -- pin all eight."""

    def test_the_full_eight_entry_mapping_is_declared(self) -> None:
        assert load_remap_script().TABLE_TO_WAREHOUSE_CODE == {
            "stock_almacen_ayb": "STOCK_ALMACEN_AYB",
            "stock_almacen_suministros": "STOCK_ALMACEN_SUMINISTROS",
            "stock_kiosco_piscigiros_ayb": "STOCK_KIOSCO_PISCIGIROS_AYB",
            "stock_kiosco_taquilla_ayb": "STOCK_KIOSCO_TAQUILLA_AYB",
            "stock_restaurante_fuentes_ayb": "STOCK_RESTAURANTE_FUENTES_AYB",
            "stock_restaurante_fuentes_sumin": "STOCK_RESTAURANTE_FUENTES_SUMIN",
            "zoologico": "ZOOLOGICO",
            "zoologico_suministros": "ZOOLOGICO_SUMINISTROS_2",
        }

    def test_the_zoologico_suministros_code_is_not_an_uppercase_of_its_table(
        self,
    ) -> None:
        """A naive `upper()` drops this warehouse's 193 rows and deflates coverage.

        Supabase carries `ZOOLOGICO_SUMINISTROS_2` -- a load-time code
        collision -- and `ZOOLOGICO_SUMINISTROS` does not exist at all.
        """
        mapping = load_remap_script().TABLE_TO_WAREHOUSE_CODE
        assert mapping["zoologico_suministros"] != "zoologico_suministros".upper()
        assert "ZOOLOGICO_SUMINISTROS" not in EXPECTED_WAREHOUSE_ROWS
        assert EXPECTED_WAREHOUSE_ROWS[mapping["zoologico_suministros"]] == 193

    def test_the_mapping_covers_exactly_the_fixture_warehouses(self) -> None:
        mapping = load_remap_script().TABLE_TO_WAREHOUSE_CODE
        assert set(mapping.values()) == set(EXPECTED_WAREHOUSE_ROWS)
